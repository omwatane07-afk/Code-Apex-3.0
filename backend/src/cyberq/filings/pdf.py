"""Byte-reproducible PDF generation with dynamic watermarks and cryptographic CRC32/short-hash check-codes."""

import io
import os
import zlib
from typing import Any

from reportlab.lib.pagesizes import A4  # type: ignore[import-untyped]
from reportlab.pdfgen import canvas  # type: ignore[import-untyped]

from cyberq.audit.chain import canonical_json


def generate_filing_pdf(
    packet_data: dict[str, Any],
    packet_hash: str,
    incident_number: str,
    approver_name: str,
    watermark_text: str = "CONFIDENTIAL BANK REGULATORY FILING - STATUTORY RECORD",
    source_date_epoch: int | None = None,
) -> bytes:
    """Generates a byte-reproducible A4 PDF of the regulatory filing packet.

    Presents:
    1. Top Banner: Printable CRC32 + Short-Hash check-code for offline paper verification.
    2. Dynamic background watermark across pages.
    3. Structured statutory tables for CERT-In, RBI DAKSH, and DPDP.
    4. Exact byte-reproducibility when source_date_epoch is pinned.
    """
    # 1. Calculate printable CRC32 check-code
    canonical_bytes = canonical_json(packet_data)
    crc32_code = f"{zlib.crc32(canonical_bytes):08X}"
    short_hash = packet_hash[:16].upper()
    verification_check_code = f"CQ-{crc32_code}-{short_hash}"

    buffer = io.BytesIO()

    # Pin SOURCE_DATE_EPOCH for byte-reproducibility
    epoch = source_date_epoch or int(os.environ.get("SOURCE_DATE_EPOCH", "1767225600"))

    c = canvas.Canvas(buffer, pagesize=A4, pageCompression=0)
    # Enforce strict byte-for-byte reproducibility
    c._doc.invariant = True
    fixed_doc_id = packet_hash[:16].encode("ascii")
    c._doc.ID = lambda self=c._doc: (fixed_doc_id, fixed_doc_id)
    width, height = A4

    # Watermark (Diagonal, subtle grey)
    c.saveState()
    c.setFont("Helvetica-Bold", 32)
    c.setFillColorRGB(0.92, 0.92, 0.92)
    c.translate(width / 2, height / 2)
    c.rotate(45)
    c.drawCentredString(0, 0, watermark_text)
    c.restoreState()

    # Top Verification Banner (Printable CRC32 check-code)
    c.setFillColorRGB(0.1, 0.15, 0.25)
    c.rect(36, height - 70, width - 72, 40, fill=1, stroke=0)
    c.setFillColorRGB(1.0, 1.0, 1.0)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(48, height - 48, f"STATUTORY FILING VERIFICATION CODE: {verification_check_code}")
    c.setFont("Helvetica", 8)
    c.drawString(48, height - 62, f"Packet Hash: {packet_hash} | Approver: {approver_name}")

    # Title & Regulator Header
    c.setFillColorRGB(0.0, 0.0, 0.0)
    c.setFont("Helvetica-Bold", 18)
    regulator = packet_data.get("regulator", "Statutory Regulator")
    c.drawString(36, height - 105, f"{regulator} Incident Filing Packet")

    c.setFont("Helvetica", 10)
    c.drawString(36, height - 125, f"Incident Identifier: {incident_number}")
    instrument = packet_data.get("instrument", "Mandatory Directions")
    c.drawString(36, height - 140, f"Statutory Instrument: {instrument}")

    # Render packet payload entries
    y = height - 175
    c.setFont("Helvetica-Bold", 12)
    c.drawString(36, y, "Ordered Regulatory Disclosure Fields:")
    y -= 20

    def _render_dict(d: dict[str, Any], indent: int = 48) -> None:
        nonlocal y
        for k, v in d.items():
            if y < 80:
                c.showPage()
                y = height - 60

            label = k.replace("_", " ").title()
            if isinstance(v, dict):
                c.setFont("Helvetica-Bold", 9)
                c.drawString(indent, y, f"[{label}]")
                y -= 14
                _render_dict(v, indent + 16)
            elif isinstance(v, list):
                c.setFont("Helvetica-Bold", 9)
                c.drawString(indent, y, f"{label}:")
                y -= 14
                for item in v:
                    c.setFont("Helvetica", 8)
                    c.drawString(indent + 12, y, f"• {item}")
                    y -= 12
            else:
                c.setFont("Helvetica-Bold", 8)
                c.drawString(indent, y, f"{label}:")
                c.setFont("Helvetica", 8)
                c.drawString(indent + 140, y, str(v)[:85])
                y -= 14

    _render_dict(packet_data)

    # Footer
    c.setFont("Helvetica-Oblique", 7)
    c.drawString(36, 36, "Generated by CYBERQ Bank Incident-to-Board Platform (Air-Gapped Edition). Embedded .cqb manifest.")
    c.drawRightString(width - 36, 36, f"Page 1 of 1 | Stamped Epoch: {epoch}")

    c.save()
    buffer.seek(0)
    return buffer.getvalue()
