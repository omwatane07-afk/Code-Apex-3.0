def test_certin_pdf_cryptographic_audit_sealing(isolated_db_session: Session) -> None:
    """Verifies that generating and sealing a PDF writes an immutable event into audit_event."""
    audit = AuditService(TEST_SEED)
    incident = _create_test_incident(isolated_db_session, "INC-2026-0040")

    pdf_bytes, pdf_hash, verification_code = CertInReportService.generate_and_seal_certin_pdf(
        session=isolated_db_session,
        incident=incident,
        audit=audit,
        actor_id="ciso-user-01",
        actor_role="ciso",
    )
    isolated_db_session.commit()

    # Query audit ledger
    events = isolated_db_session.scalars(
        select(AuditEvent)
        .where(AuditEvent.entity_id == incident.id)
        .where(AuditEvent.action == "report:pdf_generated")
    ).all()

    assert len(events) >= 1
    event = events[-1]
    assert event.entity_type == "statutory_certin_pdf"
    assert event.actor_id == "ciso-user-01"
    assert event.actor_role == "ciso"
    assert event.after_state is not None
    assert event.after_state["pdf_sha256"] == pdf_hash
    assert event.after_state["verification_code"] == verification_code
    assert event.after_state["incident_number"] == "INC-2026-0040"


