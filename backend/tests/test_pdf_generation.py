"""Tests for Automated Byte-Reproducible PDF Reporting Pipeline & RBAC Download Gate.

Validates:
1. Layout & Schema Match: CERT-In Directions Section 70B reporting format.
2. Mandatory Fields: Internal Incident Id, Statutory Trigger, Noticed At Utc,
   Severity Level, Affected Assets, Cve References, Indicators Of Compromise, Containment Actions Taken.
3. Verification Header Banner: 'STATUTORY FILING VERIFICATION CODE: CQ-<CRC32>-<ShortHash>',
   'Packet Hash' (SHA-256), and 'Approver' identity.
4. Watermark: 'CONFIDENTIAL BANK REGULATORY FILING'.
5. Footer: 'Generated by CYBERQ Bank Incident-to-Board Platform (Air-Gapped Edition)... Stamped Epoch: <epoch>'.
6. Byte-Reproducibility: Identical input yields identical SHA-256 hash.
7. Cryptographic Sealing: PDF hash recorded into audit_event ledger.
8. RBAC Download Gate: CISO, Compliance Approver, and Auditor can download (200 OK, application/pdf).
   L1 Analyst is blocked (403 Forbidden).
"""

