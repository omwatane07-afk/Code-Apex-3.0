def test_certin_pdf_byte_reproducibility(isolated_db_session: Session) -> None:
    """Verifies that compiling the exact same incident yields byte-identical PDF output."""
    incident = _create_test_incident(isolated_db_session, "INC-2026-0020")
    report_data = CertInReportService.bind_incident_data(incident=incident)

    pinned_epoch = 1767225600
    pdf_1, hash_1, code_1 = CertInReportService.generate_pdf_bytes(report_data, source_date_epoch=pinned_epoch)
    pdf_2, hash_2, code_2 = CertInReportService.generate_pdf_bytes(report_data, source_date_epoch=pinned_epoch)

    # 1. Exact byte-for-byte reproducibility
    assert pdf_1 == pdf_2
    assert hash_1 == hash_2
    assert len(hash_1) == 64
    assert hash_1 == hashlib.sha256(pdf_1).hexdigest()

    # 2. Verification Code format: CQ-<CRC32>-<ShortHash>
    assert code_1 == code_2
    assert code_1.startswith("CQ-")
    parts = code_1.split("-")
    assert len(parts) == 3
    assert len(parts[1]) == 8  # 8-char CRC32 hex
    assert len(parts[2]) == 16  # 16-char short hash

    # 3. Valid PDF Magic Bytes
    assert pdf_1.startswith(b"%PDF-")


